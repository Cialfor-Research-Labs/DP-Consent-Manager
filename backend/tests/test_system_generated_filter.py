from fastapi.testclient import TestClient


class TestSystemGeneratedEmailFilter(unittest.TestCase):
    """
    Test suite verifying that system-generated receipts/replies/notifications
    are ignored without polluting the database, while genuine incoming
    fiduciary requests (healthcare, banking, education, fintech) are properly ingested.
    """

    @classmethod
    def setUpClass(cls):
        cls.test_db_path = create_isolated_test_db()
        assert_not_production_db()
        cls.webhook_secret = os.getenv("GMAIL_WEBHOOK_SECRET", "test-secret-filter-123")
        os.environ["GMAIL_WEBHOOK_SECRET"] = cls.webhook_secret
        cls.client = TestClient(app)

    @classmethod
    def tearDownClass(cls):
        destroy_isolated_test_db(cls.test_db_path)

    def setUp(self):
        assert_not_production_db()
        self.headers = {"X-Webhook-Secret": self.webhook_secret}

    def test_system_generated_consent_receipt_is_ignored(self):
        """
        A system-generated status receipt with 'DIGITAL CONSENT STATUS UPDATE'
        and 'SHA-256 Integrity Hash' must be ignored and create 0 rows in DB.
        """
        unique_msg_id = f"test_sys_{uuid.uuid4().hex[:12]}"
        payload = {
            "from_address": "compliance@education.com",
            "to_address": "Data Principal <user@example.com>",
            "subject": "Re: Action Required: Student Academic Records Consent",
            "body_text": (
                "=== DIGITAL CONSENT STATUS UPDATE ===\n"
                "Decision: CONSENT GRANTED\n"
                "Notice ID: NTC-2026-TEST-101\n"
                "Artifact ID: CNST-2026-9999\n"
                "SHA-256 Integrity Hash: sha256:abc123456789\n"
                "Generated by Data Principal Consent Manager\n"
            ),
            "fiduciary_name": "ABC Institute",
            "message_id": unique_msg_id,
            "thread_id": "thd_sys_1"
        }

        res = self.client.post("/api/gmail-webhook", json=payload, headers=self.headers)
        self.assertEqual(res.status_code, 200)
        data = res.json()

        self.assertTrue(data.get("ignored"), f"Expected ignored=True, got: {data}")
        self.assertEqual(data.get("reason"), "system_generated_message")

        # Verify no consent request was created
        conn = get_db()
        c = conn.cursor()
        c.execute("SELECT COUNT(*) FROM consent_requests WHERE message_id = ?;", (unique_msg_id,))
        count = c.fetchone()[0]
        conn.close()
        self.assertEqual(count, 0, "No consent_request should be created for system-generated receipts")

