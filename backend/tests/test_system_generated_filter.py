    def test_genuine_healthcare_request_is_ingested(self):
        """
        Genuine incoming healthcare consent request must be accepted and classified under Healthcare.
        """
        unique_msg_id = f"test_real_health_{uuid.uuid4().hex[:12]}"
        payload = {
            "from_address": "Apollo Health Center <compliance@apollohealth.org>",
            "to_address": "Patient Sharma <patient@example.com>",
            "subject": "Action Required: Consent for Healthcare Data Processing",
            "body_text": (
                "Dear Patient,\n\n"
                "Apollo Health Center requires your consent for processing diagnostic lab reports "
                "and medical treatment history in accordance with the DPDP Act 2023.\n\n"
                "Please review and submit your decision."
            ),
            "message_id": unique_msg_id,
        }

        res = self.client.post("/api/gmail-webhook", json=payload, headers=self.headers)
        self.assertEqual(res.status_code, 200)
        data = res.json()

        self.assertFalse(data.get("ignored", False), f"Genuine healthcare request should NOT be ignored: {data}")
        self.assertEqual(data.get("domain"), "Healthcare")
        self.assertTrue(data.get("token", "").startswith("tok_"))

        conn = get_db()
        c = conn.cursor()
        c.execute("SELECT COUNT(*) FROM consent_requests WHERE message_id = ?;", (unique_msg_id,))
        count = c.fetchone()[0]
        conn.close()
        self.assertEqual(count, 1, "Genuine healthcare request must create exactly 1 consent_request")

