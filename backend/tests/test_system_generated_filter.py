    def test_genuine_request_idempotency_preserved(self):
        """
        Posting the same genuine incoming request twice returns the same token and request ID.
        """
        unique_msg_id = f"test_real_idemp_{uuid.uuid4().hex[:12]}"
        payload = {
            "from_address": "Apollo Health Center <compliance@apollohealth.org>",
            "to_address": "Patient <patient@example.com>",
            "subject": "Action Required: Consent for Healthcare Data Processing",
            "body_text": "Healthcare consent request details...",
            "message_id": unique_msg_id,
        }

        res1 = self.client.post("/api/gmail-webhook", json=payload, headers=self.headers)
        self.assertEqual(res1.status_code, 200)
        data1 = res1.json()

        res2 = self.client.post("/api/gmail-webhook", json=payload, headers=self.headers)
        self.assertEqual(res2.status_code, 200)
        data2 = res2.json()

        self.assertEqual(data1["token"], data2["token"])
        self.assertEqual(data1["id"], data2["id"])

        conn = get_db()
        c = conn.cursor()
        c.execute("SELECT COUNT(*) FROM consent_requests WHERE message_id = ?;", (unique_msg_id,))
        count = c.fetchone()[0]
        conn.close()
        self.assertEqual(count, 1, "Idempotency must prevent duplicate consent_requests")


